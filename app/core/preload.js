const { contextBridge, ipcRenderer } = require('electron');
const on = (ch, fn) => { const h = (_e, d) => fn(d); ipcRenderer.on(ch, h); return () => ipcRenderer.removeListener(ch, h); };
contextBridge.exposeInMainWorld('api', {
  init: () => ipcRenderer.invoke('init'),
  patchConfig: p => ipcRenderer.invoke('config:patch', p),
  setConfig: (k, v) => ipcRenderer.invoke('config:set', k, v),
  resetConfig: s => ipcRenderer.invoke('config:reset', s),
  defaultContent: () => ipcRenderer.invoke('content:default'),
  connect: u => ipcRenderer.invoke('tiktok:connect', u),
  disconnect: () => ipcRenderer.invoke('tiktok:disconnect'),
  tts: (t, o) => ipcRenderer.invoke('tts', t, o),
  ttsTest: e => ipcRenderer.invoke('tts:test', e),
  vieneu: { status: () => ipcRenderer.invoke('vieneu:status'), install: () => ipcRenderer.invoke('vieneu:install'), start: () => ipcRenderer.invoke('vieneu:start'), stop: () => ipcRenderer.invoke('vieneu:stop'), test: r => ipcRenderer.invoke('vieneu:test', r), clone: o => ipcRenderer.invoke('vieneu:clone', o), prerender: () => ipcRenderer.invoke('vieneu:prerender') },
  ttsClear: () => ipcRenderer.invoke('tts:clear'),
  ttsCount: () => ipcRenderer.invoke('tts:count'),
  avatar: u => ipcRenderer.invoke('avatar', u),
  simulate: ev => ipcRenderer.send('simulate', ev),
  stageCmd: c => ipcRenderer.send('stage:cmd', c),
  report: d => ipcRenderer.send('stage:report', d),
  saveState: (n, d) => ipcRenderer.send('state:save', n, d),
  loadState: n => ipcRenderer.invoke('state:load', n),
  log: (m, l) => ipcRenderer.send('log', m, l),
  openStage: () => ipcRenderer.invoke('stage:open'),
  closeStage: () => ipcRenderer.invoke('stage:close'),
  stageSet: o => ipcRenderer.invoke('stage:set', o),
  openDialog: o => ipcRenderer.invoke('dialog:open', o),
  fileDataURL: p => ipcRenderer.invoke('file:dataurl', p),
  addVideo: f => ipcRenderer.invoke('video:add', f),
  removeVideo: id => ipcRenderer.invoke('video:remove', id),
  addMusic: f => ipcRenderer.invoke('music:add', f),
  removeMusic: id => ipcRenderer.invoke('music:remove', id),
  saveCharacter: o => ipcRenderer.invoke('character:save', o),
  cloneCharacter: id => ipcRenderer.invoke('character:clone', id),
  deleteCharacter: id => ipcRenderer.invoke('character:delete', id),
  saveFrame: o => ipcRenderer.invoke('frame:save', o),
  deleteFrame: id => ipcRenderer.invoke('frame:delete', id),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  applyUpdate: () => ipcRenderer.invoke('update:apply'),
  rollback: () => ipcRenderer.invoke('update:rollback'),
  exportConfig: () => ipcRenderer.invoke('config:export'),
  importConfig: () => ipcRenderer.invoke('config:import'),
  openUserDir: () => ipcRenderer.invoke('open:userdir'),
  relaunch: () => ipcRenderer.invoke('app:relaunch'),
  on,
});
